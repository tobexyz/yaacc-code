package de.yaacc.upnp.server.contentdirectory;

import android.content.Context;

import org.fourthline.cling.support.model.DIDLObject;
import org.fourthline.cling.support.model.SortCriterion;
import org.fourthline.cling.support.model.container.Container;
import org.fourthline.cling.support.model.container.StorageFolder;
import org.fourthline.cling.support.model.item.Item;

import java.util.ArrayList;
import java.util.List;

import de.yaacc.R;

/** "All videos": every video in the media paths. */
public class VideosAllFolderBrowser extends VideoBrowser {

    public VideosAllFolderBrowser(Context context) {
        super(context);
    }

    @Override
    public DIDLObject browseMeta(YaaccContentDirectory contentDirectory, String myId, long firstResult, long maxResults, SortCriterion[] orderby) {
        return new StorageFolder(ContentDirectoryIDs.VIDEOS_ALL_FOLDER.getId(), ContentDirectoryIDs.VIDEOS_FOLDER.getId(),
                getContext().getString(R.string.all_videos), "yaacc", getSize(contentDirectory, myId), null);
    }

    @Override
    public Integer getSize(YaaccContentDirectory contentDirectory, String myId) {
        return count(contentDirectory, mediaPathSelection(), mediaPathArguments());
    }

    @Override
    public List<Container> browseContainer(YaaccContentDirectory contentDirectory, String myId, long firstResult, long maxResults, SortCriterion[] orderby) {
        return new ArrayList<>();
    }

    @Override
    public List<Item> browseItem(YaaccContentDirectory contentDirectory, String myId, long firstResult, long maxResults, SortCriterion[] orderby) {
        return items(contentDirectory, mediaPathSelection(), mediaPathArguments(), ContentDirectoryIDs.VIDEOS_ALL_FOLDER.getId(),
                firstResult, maxResults, orderby);
    }
}
