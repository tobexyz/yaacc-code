package de.yaacc.openhome;

/** Text for the content of an XML element: the five special characters escaped, characters that XML 1.0 does not allow dropped. */
public final class OhEscape {
    private OhEscape() {
    }

    public static String xml(String text) {
        if (text == null) {
            return "";
        }
        StringBuilder out = new StringBuilder(text.length() + 16);
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '&':
                    out.append("&amp;");
                    break;
                case '<':
                    out.append("&lt;");
                    break;
                case '>':
                    out.append("&gt;");
                    break;
                case '"':
                    out.append("&quot;");
                    break;
                case '\'':
                    out.append("&apos;");
                    break;
                default:
                    if (c == 0x9 || c == 0xA || c == 0xD || (c >= 0x20 && c <= 0xD7FF) || (c >= 0xE000 && c <= 0xFFFD)
                            || Character.isHighSurrogate(c) || Character.isLowSurrogate(c)) {
                        out.append(c);
                    }
                    break;
            }
        }
        return out.toString();
    }
}
